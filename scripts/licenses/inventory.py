#!/usr/bin/env python3
"""Third-party license inventory for the Android FOSS runtime classpath (Gradle).
Usage: python3 -I scripts/licenses/inventory.py <gradle-dependencies-output.txt> > docs/THIRD_PARTY_NOTICES.md
Then re-add the Haskell section (this command overwrites the whole file): python3 -I scripts/licenses/haskell_inventory.py --write
Reads licenses from POM files in the local Gradle cache (follows parent POMs). Artifacts whose POM is missing
or declares no license are listed as UNKNOWN and must be reviewed by hand."""
import re, sys, glob, os, collections
import xml.etree.ElementTree as ET
CACHE = os.path.expanduser("~/.gradle/caches/modules-2/files-2.1")
coords = {}
for line in open(sys.argv[1]):
    m = re.match(r"^[|+\\ -]*([\w.\-]+):([\w.\-]+):([\w.\-+]+)(?: -> ([\w.\-+]+))?", line)
    if m and "(c)" not in line and "(n)" not in line:
        g, a, v, v2 = m.groups()
        coords[(g, a)] = v2 or v
def pom_path(g, a, v):
    hits = glob.glob(f"{CACHE}/{g}/{a}/{v}/*/*.pom")
    return hits[0] if hits else None
def strip(t): return re.sub(r"\{[^}]*\}", "", t)
def licenses(g, a, v, depth=0):
    p = pom_path(g, a, v)
    if not p: return None
    try: root = ET.parse(p).getroot()
    except Exception: return None
    names = []
    for el in root.iter():
        if strip(el.tag) == "license":
            n = next((c.text for c in el if strip(c.tag) == "name" and c.text), None)
            u = next((c.text for c in el if strip(c.tag) == "url" and c.text), None)
            names.append((n or u or "").strip())
    if names: return names
    if depth < 4:
        par = next((e for e in root if strip(e.tag) == "parent"), None)
        if par is not None:
            pg, pa, pv = (next((c.text for c in par if strip(c.tag) == k), None) for k in ("groupId", "artifactId", "version"))
            if pg and pa and pv: return licenses(pg, pa, pv, depth + 1)
    return None
rows, unknown, by = [], [], collections.Counter()
for (g, a), v in sorted(coords.items()):
    ls = licenses(g, a, v)
    if ls:
        rows.append((g, a, v, "; ".join(dict.fromkeys(ls)))); by[ls[0]] += 1
    else:
        unknown.append((g, a, v))
print("# Third-party notices (generated)\n")
print("Generated by `scripts/licenses/inventory.py` from the resolved `fossDebugRuntimeClasspath` of `:android` and the local Gradle cache POMs. This part covers the Gradle/Kotlin classpath only; the Haskell core and native libraries (`libsimplex.so`, `libsupport.so`) are in the last section, generated by `scripts/licenses/haskell_inventory.py`. Do not edit by hand; regenerate.\n")
print(f"Artifacts: {len(coords)}; with declared license: {len(rows)}; UNKNOWN (needs manual review): {len(unknown)}\n")
print("## License summary\n\n| License (first declared) | Artifacts |\n|---|---|")
for n, c in by.most_common(): print(f"| {n} | {c} |")
print("\n## Artifacts\n\n| Artifact | Version | License |\n|---|---|---|")
for g, a, v, l in rows: print(f"| {g}:{a} | {v} | {l} |")
if unknown:
    print("\n## UNKNOWN license (manual review required)\n")
    for g, a, v in unknown: print(f"- {g}:{a}:{v}")
